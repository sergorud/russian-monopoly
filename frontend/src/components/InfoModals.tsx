/**
 * Окно с описанием специальной клетки
 */
export function CellInfoModal({ cellId, onClose }: { cellId: number; onClose: () => void }) {
  const info = CELL_DESCRIPTIONS[cellId];
  if (!info) return null;

  return (
    <div style={overlayStyle} onClick={onClose}>
      <div style={cardStyle} onClick={(e) => e.stopPropagation()}>
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '12px' }}>
          <h3 style={{ margin: 0, fontSize: '18px', color: '#333' }}>
            {info.icon} {info.title}
          </h3>
          <button onClick={onClose} style={closeBtnStyle}>✕</button>
        </div>
        {info.text.map((paragraph, i) => (
          <p key={i} style={{ margin: '0 0 10px 0', fontSize: '14px', color: '#444', lineHeight: 1.5 }}>
            {paragraph}
          </p>
        ))}
        <button onClick={onClose} style={okBtnStyle}>Понятно</button>
      </div>
    </div>
  );
}

/**
 * Карточка недвижимости: цены, цены домов/отелей, таблица аренды, текущий статус
 */
export function PropertyInfoModal({ cellId, gameState, onClose }: { cellId: number; gameState: GameState; onClose: () => void }) {
  const cell = BOARD[cellId] as PropertyCell;
  if (!cell || (cell.type !== 'property' && cell.type !== 'railroad' && cell.type !== 'utility')) return null;

  const property = gameState.properties[cellId];
  const owner = property?.ownerId ? gameState.players.find(p => p.id === property.ownerId) ?? null : null;

  const rentRows: [string, number][] =
    cell.type === 'property'
      ? [
          ['Без домов', cell.rent[0]],
          ['1 дом', cell.rent[1]],
          ['2 дома', cell.rent[2]],
          ['3 дома', cell.rent[3]],
          ['4 дома', cell.rent[4]],
          ['🏨 Отель', cell.rent[5]],
        ]
      : cell.type === 'railroad'
        ? [
            ['1 дорога', cell.rent[0]],
            ['2 дороги', cell.rent[1]],
            ['3 дороги', cell.rent[2]],
            ['4 дороги', cell.rent[3]],
          ]
        : [];

  return (
    <div style={overlayStyle} onClick={onClose}>
      <div style={cardStyle} onClick={(e) => e.stopPropagation()}>
        {/* Шапка: цвет группы + название */}
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '10px' }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
            <div style={{ width: '16px', height: '16px', borderRadius: '4px', background: getColorHex(cell.color), border: '1px solid #333' }} />
            <h3 style={{ margin: 0, fontSize: '18px', color: '#333' }}>{cell.name}</h3>
          </div>
          <button onClick={onClose} style={closeBtnStyle}>✕</button>
        </div>

        {/* Текущий статус */}
        <div style={{ padding: '8px 10px', background: owner ? '#fff9c4' : '#e8f5e9', borderRadius: '8px', fontSize: '13px', color: '#444', marginBottom: '10px' }}>
          {owner ? <>👤 Владелец: <b>{owner.name}</b></> : <>✅ Свободна — можно купить</>}
          {property && property.houses > 0 && <> · {property.houses === 5 ? '🏨 отель' : `🏠 домов: ${property.houses}`}</>}
          {property?.isMortgaged && <> · 📜 в залоге</>}
        </div>

        {/* Цены */}
        <InfoRow label="💵 Цена покупки" value={`$${cell.price}`} />
        {cell.type === 'property' && (
          <>
            <InfoRow label="🏠 Цена дома" value={`$${cell.houseCost}`} />
            <InfoRow label="🏨 Цена отеля" value={`$${cell.houseCost} (после 4 домов; всего $${cell.houseCost * 5})`} />
          </>
        )}

        {/* Таблица аренды */}
        {rentRows.length > 0 && (
          <div style={{ border: '1px solid #eee', borderRadius: '8px', overflow: 'hidden', marginTop: '10px' }}>
            {rentRows.map(([label, value], i) => (
              <div key={i} style={{ display: 'flex', justifyContent: 'space-between', padding: '6px 10px', fontSize: '13px', background: i % 2 ? '#fafafa' : '#ffffff' }}>
                <span style={{ color: '#555' }}>{label}</span>
                <b style={{ color: '#e30613' }}>${value}</b>
              </div>
            ))}
          </div>
        )}

        {cell.type === 'property' && (
          <p style={{ margin: '8px 0 0 0', fontSize: '12px', color: '#666' }}>
            💡 При монополии (все улицы цвета у одного игрока) аренда без домов удваивается: <b>${cell.rent[0] * 2}</b>.
          </p>
        )}

        {cell.type === 'utility' && (
          <p style={{ margin: '8px 0 0 0', fontSize: '13px', color: '#444', lineHeight: 1.5 }}>
            Аренда = сумма кубиков × <b>{cell.rent[0]}</b> (одно предприятие у владельца) или × <b>{cell.rent[1]}</b> (оба предприятия).
          </p>
        )}

        <button onClick={onClose} style={okBtnStyle}>Закрыть</button>
      </div>
    </div>
  );
}

